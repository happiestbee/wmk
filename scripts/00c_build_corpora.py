#!/usr/bin/env python3
"""Phase 0: build the prose / factual / code corpora.

Every source predates 2022 by construction, which is what makes the Phase 5.4
empirical null a true null: no document here can already carry a watermark.

    prose    sedthh/gutenberg_english        Project Gutenberg, public domain (pre-1929)
    factual  rajpurkar/squad                 Wikipedia passages, 2016
    code     codeparrot/codeparrot-clean-valid  GitHub dump 2021, permissive licenses only

    python scripts/00c_build_corpora.py --seed 0
"""

from __future__ import annotations

import argparse
import ast
import io
import json
import re
import sys
import tokenize
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from wmk.config import canonical_json
from wmk.registry import REPO_ROOT, sha256_file

CORPORA_DIR = REPO_ROOT / "data" / "corpora"
LENGTH_TOKENIZER = "Qwen/Qwen2.5-0.5B"

SOURCES = {
    "prose": {"dataset": "sedthh/gutenberg_english", "split": "train", "provenance": "Project Gutenberg, public domain, published pre-1929"},
    "factual": {"dataset": "rajpurkar/squad", "split": "train", "provenance": "Wikipedia passages via SQuAD v1.1, 2016"},
    "code": {"dataset": "codeparrot/codeparrot-clean-valid", "split": "train", "provenance": "GitHub Python dump 2021, permissive licenses, non-autogenerated"},
}
PERMISSIVE = {"mit", "apache-2.0", "bsd-3-clause", "bsd-2-clause", "isc", "0bsd", "unlicense"}

# Library of Congress classes for literature. Without this filter the stream's low
# text_ids dominate and the prose domain fills with constitutions, treaties and
# inaugural addresses -- factual text under a prose label.
NARRATIVE_LOCC = ("PR", "PS", "PZ", "PQ", "PT", "PN")

GUTENBERG_START = re.compile(r"\*\*\*\s*START OF (THE|THIS) PROJECT GUTENBERG EBOOK.*?\*\*\*", re.I | re.S)
GUTENBERG_END = re.compile(r"\*\*\*\s*END OF (THE|THIS) PROJECT GUTENBERG EBOOK.*", re.I | re.S)
PRODUCED_BY = re.compile(r"^\s*(Produced by|Transcribed from|E-text prepared by).*$", re.I | re.M)


def strip_gutenberg_boilerplate(text: str) -> str:
    """Shared licence text across every book would recur as identical context in every
    prose document, inflating the masked fraction of the whole domain."""
    m = GUTENBERG_START.search(text)
    if m:
        text = text[m.end():]
    text = GUTENBERG_END.split(text)[0]
    text = PRODUCED_BY.sub("", text)
    return text.replace("\r\n", "\n").strip()


def comment_char_spans(src: str) -> list[list[int]]:
    """Character ranges of comments and docstrings, merged and sorted, so Phase 3 can
    split code-line from comment-line positions via tokenizer offsets."""
    line_start = [0]
    for line in src.splitlines(keepends=True):
        line_start.append(line_start[-1] + len(line))

    def abs_off(row: int, col: int) -> int:
        return line_start[row - 1] + col

    spans: list[tuple[int, int]] = []
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT:
            spans.append((abs_off(*tok.start), abs_off(*tok.end)))

    for node in ast.walk(ast.parse(src)):
        if not isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        body = getattr(node, "body", None)
        if not body:
            continue
        first = body[0]
        if (
            isinstance(first, ast.Expr)
            and isinstance(first.value, ast.Constant)
            and isinstance(first.value.value, str)
        ):
            spans.append(
                (abs_off(first.lineno, first.col_offset), abs_off(first.end_lineno, first.end_col_offset))
            )

    spans.sort()
    merged: list[list[int]] = []
    for start, end in spans:
        if merged and start <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], end)
        else:
            merged.append([start, end])
    return merged


def _window(text: str, tok, rng, min_tokens: int, max_tokens: int) -> str | None:
    """A contiguous excerpt whose length lands in range, taken from a seeded offset."""
    if len(text) < min_tokens * 2:
        return None
    lo = int(rng.integers(0, max(1, len(text) - min_tokens * 6)))
    chunk = text[lo:lo + max_tokens * 8]
    # Gutenberg texts are hard-wrapped with blank lines, so a paragraph break is a
    # poor sentence boundary; seek a real one instead.
    boundary = re.search(r'(?<=[.!?"])\s+(?=[A-Z"“])', chunk[:2000])
    if boundary:
        chunk = chunk[boundary.end():]
    ids = tok(chunk, add_special_tokens=False).input_ids
    if len(ids) < min_tokens:
        return None
    if len(ids) > max_tokens:
        chunk = tok.decode(ids[:max_tokens])
        cut = chunk.rfind(".")
        if cut > len(chunk) // 2:
            chunk = chunk[: cut + 1]
    ids = tok(chunk, add_special_tokens=False).input_ids
    return chunk if min_tokens <= len(ids) <= max_tokens else None


def build_prose(tok, rng, n_docs, min_tokens, max_tokens):
    from datasets import load_dataset

    ds = load_dataset(SOURCES["prose"]["dataset"], split="train", streaming=True)
    docs, seen = [], set()
    for row in ds:
        if len(docs) >= n_docs:
            break
        meta = json.loads(row["METADATA"]) if isinstance(row["METADATA"], str) else row["METADATA"]
        if meta.get("language") != "en":
            continue
        text_id = meta.get("text_id")
        if text_id in seen:
            continue
        locc = {c.strip()[:2] for c in str(meta.get("locc", "")).split(";") if c.strip()}
        subjects = str(meta.get("subjects", "")).lower()
        if not (locc & set(NARRATIVE_LOCC) or "fiction" in subjects):
            continue
        body = strip_gutenberg_boilerplate(row["TEXT"] or "")
        chunk = _window(body, tok, rng, min_tokens, max_tokens)
        if chunk is None:
            continue
        seen.add(text_id)
        docs.append(
            {
                "domain": "prose",
                "subdomain": "narrative",
                "source_ref": f"gutenberg:{text_id}",
                "title": str(meta.get("title", ""))[:200].replace("\r\n", " "),
                "text": chunk,
            }
        )
    return docs


def build_factual(tok, rng, n_docs, min_tokens, max_tokens):
    from datasets import load_dataset

    ds = load_dataset(SOURCES["factual"]["dataset"], split="train", streaming=True)
    by_title: dict[str, list[str]] = {}
    qa_by_title: dict[str, list[tuple[str, str]]] = {}
    for row in ds:
        title = row["title"]
        ctxs = by_title.setdefault(title, [])
        if row["context"] not in ctxs:
            ctxs.append(row["context"])
        answers = row["answers"]["text"]
        if answers:
            qa_by_title.setdefault(title, []).append((row["question"], answers[0]))
        if len(by_title) > n_docs * 3 and sum(len(v) for v in by_title.values()) > n_docs * 30:
            break

    titles = sorted(by_title)
    rng.shuffle(titles)
    n_qa = n_docs // 4
    docs = []

    for title in titles:
        if len(docs) >= n_docs:
            break
        want_qa = len(docs) >= n_docs - n_qa
        if want_qa:
            pairs = qa_by_title.get(title, [])
            if len(pairs) < 8:
                continue
            body = "\n\n".join(f"Q: {q}\nA: {a}" for q, a in pairs[:60])
            subdomain = "qa"
        else:
            body = "\n\n".join(by_title[title])
            subdomain = "encyclopedic"

        ids = tok(body, add_special_tokens=False).input_ids
        if len(ids) < min_tokens:
            continue
        if len(ids) > max_tokens:
            body = tok.decode(ids[:max_tokens])
            cut = body.rfind("\n\n")
            if cut > min_tokens:
                body = body[:cut]
        ids = tok(body, add_special_tokens=False).input_ids
        if not min_tokens <= len(ids) <= max_tokens:
            continue
        docs.append(
            {
                "domain": "factual",
                "subdomain": subdomain,
                "source_ref": f"squad:{title}",
                "title": title.replace("_", " "),
                "text": body,
            }
        )
    return docs


def build_code(tok, rng, n_docs, min_tokens, max_tokens):
    from datasets import load_dataset

    ds = load_dataset(SOURCES["code"]["dataset"], split="train", streaming=True)
    docs, seen_repos = [], {}
    for row in ds:
        if len(docs) >= n_docs:
            break
        if str(row.get("autogenerated")).lower() == "true":
            continue
        if (row.get("license") or "").lower() not in PERMISSIVE:
            continue
        repo = row["repo_name"]
        if seen_repos.get(repo, 0) >= 3:
            continue
        content = row["content"] or ""
        ids = tok(content, add_special_tokens=False).input_ids
        if not min_tokens <= len(ids) <= max_tokens:
            continue
        try:
            spans = comment_char_spans(content)
        except (SyntaxError, tokenize.TokenError, IndentationError, ValueError):
            continue
        seen_repos[repo] = seen_repos.get(repo, 0) + 1
        docs.append(
            {
                "domain": "code",
                "subdomain": "python",
                "source_ref": f"{repo}:{row['path']}",
                "title": row["path"],
                "license": row["license"],
                "comment_char_spans": spans,
                "text": content,
            }
        )
    return docs


BUILDERS = {"prose": build_prose, "factual": build_factual, "code": build_code}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--n-docs", type=int, default=200)
    ap.add_argument("--min-tokens", type=int, default=300)
    ap.add_argument("--max-tokens", type=int, default=2000)
    ap.add_argument("--domains", nargs="*", default=list(BUILDERS))
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    from transformers import AutoTokenizer

    CORPORA_DIR.mkdir(parents=True, exist_ok=True)
    tok = AutoTokenizer.from_pretrained(REPO_ROOT / "data" / "weights" / LENGTH_TOKENIZER.replace("/", "__"))

    manifest_path = CORPORA_DIR / "MANIFEST_corpora.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {"schema_version": 1, "domains": {}}
    manifest["length_tokenizer"] = LENGTH_TOKENIZER
    manifest["params"] = {"seed": args.seed, "n_docs": args.n_docs, "min_tokens": args.min_tokens, "max_tokens": args.max_tokens}

    for domain in args.domains:
        out = CORPORA_DIR / f"{domain}.jsonl"
        if out.exists() and not args.force:
            print(f"skip {domain} (exists)")
            continue

        rng = np.random.default_rng([args.seed, sum(domain.encode())])
        print(f"building {domain} from {SOURCES[domain]['dataset']} ...", flush=True)
        docs = BUILDERS[domain](tok, rng, args.n_docs, args.min_tokens, args.max_tokens)

        lengths = []
        with open(out, "w", encoding="utf-8") as fh:
            for i, doc in enumerate(docs):
                n_tok = len(tok(doc["text"], add_special_tokens=False).input_ids)
                lengths.append(n_tok)
                doc = {"doc_id": f"{domain}-{i:04d}", "n_tokens": n_tok, **doc}
                fh.write(canonical_json(doc) + "\n")

        arr = np.array(lengths) if lengths else np.array([0])
        manifest["domains"][domain] = {
            **SOURCES[domain],
            "path": str(out.relative_to(REPO_ROOT)),
            "sha256": sha256_file(out),
            "n_docs": len(docs),
            "tokens_total": int(arr.sum()),
            "tokens_mean": round(float(arr.mean()), 1),
            "tokens_min": int(arr.min()),
            "tokens_max": int(arr.max()),
        }
        d = manifest["domains"][domain]
        print(f"  {d['n_docs']} docs, {d['tokens_total']} tokens, mean {d['tokens_mean']} (min {d['tokens_min']}, max {d['tokens_max']})")
        manifest_path.write_text(canonical_json(manifest) + "\n", encoding="utf-8")

    manifest_path.write_text(canonical_json(manifest) + "\n", encoding="utf-8")
    print(f"wrote {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
